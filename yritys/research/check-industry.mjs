// Toimialavalinnan regressiotesti: ajettava Node.js:lla ilman verkkopalvelinta.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const read = name => fs.readFileSync(new URL(name, root), 'utf8');
const app = read('app.js');
const context = {window: {}};
vm.createContext(context);
vm.runInContext(read('data.js') + app.slice(0, app.lastIndexOf('boot();')), context);
vm.runInContext(`
const check=(yes,msg)=>{if(!yes) throw Error(msg)};
const equals=(got,expected)=>got.length===expected.length&&got.every(x=>expected.includes(x));
state=fresh();
check(state.industry===''&&state.all&&state.features.length===0,'initial state');
selectIndustry('tourism');
check(state.industry==='tourism'&&!state.all,'initial industry');
check(equals(state.features,M.industries.tourism.features),'tourism default dependencies');
selectIndustry('industry');
check(equals(state.features,M.industries.industry.features),'second industry changes suggestions');
selectIndustry('services');
check(equals(state.features,M.industries.services.features),'third industry changes suggestions');
state.features.push('winter');
state.customFeatures=true;
selectIndustry('tourism');
check(equals(state.features,['premises','winter']),'manual features preserved on industry change');
restoreIndustryFeatures();
check(!state.customFeatures&&equals(state.features,M.industries.tourism.features),'restore current industry defaults');
selectIndustry('');
check(state.industry===''&&state.all&&state.features.length===0,'empty sector resets automatic suggestions');
state=fresh();
check(state.industry===''&&state.all&&state.features.length===0&&!state.customFeatures,'reset clears selection');
check(M.version==='1.2','version 1.2');
`, context);
const html = read('index.html');
assert(html.includes('id="reset" class="suite-reset"'), 'reset in top navigation');
assert.equal((html.match(/id="reset"/g) || []).length, 1, 'reset appears once');
assert(html.includes('versio 1.2'), 'footer version');
console.log('PASS: toistuvat toimialavaihdot, omien riippuvuuksien säilytys, oletusten palautus, tyhjennys ja versio 1.2.');
